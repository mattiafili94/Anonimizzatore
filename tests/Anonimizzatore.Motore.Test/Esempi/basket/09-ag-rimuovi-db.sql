-- Rimuovere un database dal gruppo AGZeta
ALTER AVAILABILITY GROUP [AGZeta] REMOVE DATABASE [VenditeZeta];
GO
-- Su una replica secondaria: toglie solo la copia locale
ALTER DATABASE [VenditeZeta] SET HADR OFF;
GO
ALTER AVAILABILITY GROUP [AGZeta] MODIFY REPLICA ON N'SRVSQL02' WITH (AVAILABILITY_MODE = SYNCHRONOUS_COMMIT, FAILOVER_MODE = AUTOMATIC);
ALTER AVAILABILITY GROUP [AGZeta] FAILOVER;
ALTER AVAILABILITY GROUP [AGZeta] REMOVE REPLICA ON N'SRVSQL03';
ALTER AVAILABILITY GROUP [AGZeta] ADD LISTENER N'LSNZeta' (WITH IP ((N'10.20.30.40', N'255.255.255.0')), PORT = 1433);
GO
CREATE AVAILABILITY GROUP [AGZeta2]
WITH (AUTOMATED_BACKUP_PREFERENCE = SECONDARY)
FOR DATABASE [VenditeZeta]
REPLICA ON
  N'SRVSQL01' WITH (ENDPOINT_URL = N'TCP://srvsql01.zeta.local:5022', AVAILABILITY_MODE = SYNCHRONOUS_COMMIT, FAILOVER_MODE = AUTOMATIC),
  N'SRVSQL02' WITH (ENDPOINT_URL = N'TCP://srvsql02.zeta.local:5022', AVAILABILITY_MODE = SYNCHRONOUS_COMMIT, FAILOVER_MODE = AUTOMATIC);
GO
DROP AVAILABILITY GROUP [AGZeta2];
GO
